import { describe, expect, it } from "vitest";
import { parseTitleCandidates } from "../../src/shared/titleCandidates";

describe("parseTitleCandidates", () => {
  it("空白骨架（pipeline.cover 默认产出）返回空数组，不误抓原料/简介/标签", () => {
    const skeleton = `# 标题与简介候选

> 本文件由 \`pipeline.cover\` 抽出原料，**标题由 agent 写**，写完覆盖本节。

## 候选（5 条，注明路子）

| # | 路子 | 标题 |
|---|---|---|
| 1 | | |
| 2 | | |
| 3 | | |
| 4 | | |
| 5 | | |

## 简介

（待写）

## 标签

（待写）

---

## 原料

**稿件抬头**：为什么雪乃和大老师从来不是互补

**收束（末三段，去掉收尾语）**：

- 真正让人难受的从来不是选错了人
- 而是明明看透了一切却还装作无所谓
`;
    expect(parseTitleCandidates(skeleton)).toEqual([]);
  });

  it("解析标准 5 行候选表，保留路子标签并清理外层粗体/引号，且止于简介与原料", () => {
    const md = `# 标题与简介候选

## 候选（5 条，注明路子）

| # | 路子 | 标题 |
|---|---|---|
| 1 | 金句 | **雪乃到底适不适合大老师？** |
| 2 | 反差 | 「嘴上说不需要真物，身体却比谁都诚实」 |
| 3 | 痛点 | 为什么「真物」和「伪物」根本是一体两面 |
| 4 | 悬念 | — |
| 5 | 对比 | 看懂侍奉部这三个人，才算看懂青春恋爱物语 |

## 简介

- 第一句简介绝不该被抓进标题候选

## 标签

- 春物
- 杂谈

---

## 原料

- 原料里的句子也不能进来
`;
    expect(parseTitleCandidates(md)).toEqual([
      { label: "金句", title: "雪乃到底适不适合大老师？" },
      { label: "反差", title: "嘴上说不需要真物，身体却比谁都诚实" },
      { label: "痛点", title: "为什么「真物」和「伪物」根本是一体两面" },
      { label: "对比", title: "看懂侍奉部这三个人，才算看懂青春恋爱物语" },
    ]);
  });

  it("支持「定稿标题」置顶并自动去重，不破坏含多组引号或破折号的标题", () => {
    const md = `# 标题候选

## 定稿标题

「真物」和「伪物」之间——只差一步

（2026-08-31 用户选定。第一轮 5 条候选被退回，理由是缺辨识度。）

## 候选标题

1. 【反差】「真物」和「伪物」之间——只差一步
2. **金句**：你以为他在自爆，其实他在救场
3. 普通无标签候选标题
4. （待写）
`;
    expect(parseTitleCandidates(md)).toEqual([
      { label: "定稿", title: "「真物」和「伪物」之间——只差一步" },
      { label: "金句", title: "你以为他在自爆，其实他在救场" },
      { title: "普通无标签候选标题" },
    ]);
  });

  it("处理带封面/复盘的定稿节、引用块定稿以及「## 备选」小节", () => {
    const md = `# 标题与简介候选

## 定稿（2026-07-29）

**标题：大老师自爆，真的是一种牺牲吗？**

**封面：\`08-cover.jpg\`** —— 候选 6，1920×1080 原帧。

标题是人自己写的，不在下方五条候选里。

---

## 定稿（2026-08-03）

> # 哪个角色最适合当队友？

- **点名观众。** 这条是复盘解释，绝不能当标题。

> **它不满足旧判据**，这是一段复盘引用。

## 备选（5 条，注明路子）

| # | 路子 | 标题 |
|---|---|---|
| 1 | 下判断 | **最适合你的，是那个把你当工具人的** |
| 2 | 反问 | 你上一次被人需要，是什么时候 |
`;
    expect(parseTitleCandidates(md)).toEqual([
      { label: "定稿", title: "大老师自爆，真的是一种牺牲吗？" },
      { label: "定稿", title: "哪个角色最适合当队友？" },
      { label: "下判断", title: "最适合你的，是那个把你当工具人的" },
      { label: "反问", title: "你上一次被人需要，是什么时候" },
    ]);
  });

  it("处理行内已定标注、完整反引号/含冒号标题与空分组父项", () => {
    const md = `# 07 标题与简介

- **最终选定标题**：\`折射下的真物：残酷人际学\`
- **备选标题**：
  - \`人物志（下）：她最后说，接着\`
  - \`**对比**：整段反引号包裹不拆标签\`
  - 「【金句】完整引号内不拆方括号」
  - 《某部作品》：重逢是奇迹，遗忘才是账单
  - 某作品：两个人的纯爱，四个人的死锁
  - 对比：A 与 B 的分岔路口

---

## 封面配字

- **封面字**：\`折射中的真物\`
`;
    expect(parseTitleCandidates(md)).toEqual([
      { label: "定稿", title: "折射下的真物：残酷人际学" },
      { title: "人物志（下）：她最后说，接着" },
      { title: "**对比**：整段反引号包裹不拆标签" },
      { title: "【金句】完整引号内不拆方括号" },
      { title: "《某部作品》：重逢是奇迹，遗忘才是账单" },
      { title: "某作品：两个人的纯爱，四个人的死锁" },
      { label: "对比", title: "A 与 B 的分岔路口" },
    ]);

    const inlineFinal = `## 候选

**已定（2026-08-12）**：\`人物志（第二期·终期）\`——延续系列命名。

**定稿：前半句定稿，后半句钉死落点**（在 #1 基础上微调）
`;
    expect(parseTitleCandidates(inlineFinal)).toEqual([
      { label: "定稿", title: "人物志（第二期·终期）" },
      { label: "定稿", title: "前半句定稿，后半句钉死落点" },
    ]);
  });

  it("处理转义管道符、无表头表格首行含「标题」、围栏代码块、一级标题止位与含「标题」的排除节", () => {
    const md = `## 候选

| 1 | 对比 | 《某作品》\\| 为什么谁也救不了 |
| 2 | 金句 | 第一个标题也是真实数据 |

\`\`\`markdown
## 候选
- 代码块里的假候选
| 1 | 金句 | 代码块里的假表格 |
\`\`\`

~~~
- 波浪线代码块里的假候选
~~~

## 标题规范与注意事项

- 规范条目绝不能入选

## 标题复盘

- 复盘条目绝不能入选

## 说明：标题规范

- 带说明前缀的也不入选

## 原料（标题参考）

- 原料区哪怕带标题二字也不能入选

## 候选补充

| 标题 | 风格 |
| - | - |
| 为什么这一集封神了 | 悬念 |

\`\`\`行内三反引号不是围栏\`\`\`

- 紧跟在行内三反引号后的正常候选

# 原料

- 一级标题切停后不再收录
`;
    expect(parseTitleCandidates(md)).toEqual([
      { label: "对比", title: "《某作品》| 为什么谁也救不了" },
      { label: "金句", title: "第一个标题也是真实数据" },
      { label: "悬念", title: "为什么这一集封神了" },
      { title: "紧跟在行内三反引号后的正常候选" },
    ]);
  });
});
